export function getDashboardTranslation(lang: string): Required<DashboardTranslation> {
  let key = 'en';
  if (lang.startsWith('de-CH') || lang === 'de-CH') key = 'de-CH';
  else if (lang.startsWith('de')) key = 'de';
  else if (lang.startsWith('fr')) key = 'fr';
  else if (lang.startsWith('it')) key = 'it';
  else if (lang.startsWith('es')) key = 'es';
  else if (lang.startsWith('pt')) key = 'pt';

  const base = dashboardTranslations[key] || dashboardTranslations['en'];
  const extra = extraTranslations[key] || extraTranslations['en'];

  return { ...base, ...extra } as Required<DashboardTranslation>;
}
