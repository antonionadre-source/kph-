/** UI copy and interpolation remain plain text in every language. */
export function kaiText(language: unknown, key: KaiTextKey, params?: HomeTextParams): string {
  return translations[normalizeHomeLanguage(language)][key].replace(
    /\{([A-Za-z][A-Za-z0-9_]*)\}/g,
    (placeholder, name: string) => params && Object.prototype.hasOwnProperty.call(params, name)
      ? String(params[name]) : placeholder,
  );
}

export function kaiFieldLabel(language: unknown, field: KaiField): string {
  return fieldLabels[normalizeHomeLanguage(language)][field] ?? kaiText(language, 'unknown');
}

export function kaiServiceLabel(language: unknown, service: KaiService | null | undefined): string {
  return service && Object.prototype.hasOwnProperty.call(serviceSources, service)
    ? homeText(language, serviceSources[service]) : kaiText(language, 'noService');
}
